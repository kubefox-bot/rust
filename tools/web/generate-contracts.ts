import { mkdir } from "node:fs/promises";
import { resolve } from "node:path";
import Ajv2020 from "ajv/dist/2020";
import { _ } from "ajv";
import standaloneCode from "ajv/dist/standalone";
import { compile } from "json-schema-to-typescript";
import { formats } from "../../apps/web/src/api/formats";
import type { JSONSchema4 } from "json-schema";

export const generateContracts = async (directory: string): Promise<void> => {
  const process = Bun.spawn(
    [
      "cargo",
      "run",
      "--quiet",
      "--locked",
      "-p",
      "hmail-cleaner-protocol",
      "--example",
      "export_browser_schema",
    ],
    { stdout: "pipe", stderr: "inherit" },
  );
  const text = await new Response(process.stdout).text();
  if ((await process.exited) !== 0)
    throw new Error("Rust browser schema generation failed");
  const ajv = new Ajv2020({
    allErrors: false,
    formats,
    code: { source: true, esm: true, lines: true, formats: _`formats` },
  });
  const parsed: unknown = JSON.parse(text);
  if (
    typeof parsed !== "object" ||
    parsed === null ||
    Array.isArray(parsed) ||
    !ajv.validateSchema(parsed)
  ) {
    throw new Error("Rust exporter returned an invalid JSON Schema");
  }
  // The meta-schema validation above establishes the upstream generator's schema contract.
  const schema = parsed as JSONSchema4;
  if (!schema.properties) throw new Error("Browser allowlist is missing");
  schema.$id = "https://hmail.invalid/browser-contracts/v1";
  schema.additionalProperties = false;
  const names = Object.keys(schema.properties).sort();
  ajv.addSchema(schema);
  const exports = Object.fromEntries(
    names.map((name) => [name, `${schema.$id}#/properties/${name}`]),
  );
  const validators = `// Generated by tools/web/generate-contracts.ts. Do not edit.\nimport {formats} from '../formats';\n${standaloneCode(ajv, exports)}\n`;
  const types = await compile(schema, "BrowserContracts", {
    bannerComment: "/* Generated from Rust browser DTOs. Do not edit. */",
    additionalProperties: false,
    style: { singleQuote: true },
    maxItems: -1,
  });
  const declarations = [
    "// Generated. Do not edit.",
    'import type {ValidateFunction} from "ajv";',
    'import type {BrowserContracts} from "./browser.types";',
    ...names.map(
      (name) =>
        `export const ${name}: ValidateFunction<BrowserContracts["${name}"]>;`,
    ),
    "",
  ].join("\n");
  await mkdir(directory, { recursive: true });
  await Promise.all([
    Bun.write(
      resolve(directory, "browser.schema.json"),
      `${JSON.stringify(schema, null, 2)}\n`,
    ),
    Bun.write(resolve(directory, "browser.types.ts"), types),
    Bun.write(resolve(directory, "validators.js"), validators),
    Bun.write(resolve(directory, "validators.d.ts"), declarations),
  ]);
};
if (import.meta.main)
  await generateContracts(resolve("apps/web/src/api/generated"));
